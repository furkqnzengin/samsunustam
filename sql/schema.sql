-- Samsun Ustam veritabanı şeması (MySQL 5.7+ / MariaDB 10.3+)
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS kullanicilar (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ad VARCHAR(100) NOT NULL,
  eposta VARCHAR(190) NOT NULL UNIQUE,
  telefon VARCHAR(20) NULL,
  sifre VARCHAR(255) NOT NULL,
  rol ENUM('admin','usta') NOT NULL DEFAULT 'usta',
  son_giris DATETIME NULL,
  olusturma DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS kategoriler (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ad VARCHAR(100) NOT NULL,
  slug VARCHAR(120) NOT NULL UNIQUE,
  ikon VARCHAR(16) NOT NULL DEFAULT '🔧',
  aciklama VARCHAR(255) NULL,
  sira INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS hizmetler (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kategori_id INT UNSIGNED NOT NULL,
  ad VARCHAR(120) NOT NULL,
  slug VARCHAR(140) NOT NULL UNIQUE,
  sira INT NOT NULL DEFAULT 0,
  FOREIGN KEY (kategori_id) REFERENCES kategoriler(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS ilceler (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ad VARCHAR(60) NOT NULL,
  slug VARCHAR(80) NOT NULL UNIQUE,
  sira INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS paketler (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ad VARCHAR(80) NOT NULL,
  aciklama VARCHAR(255) NULL,
  ozellikler TEXT NULL,
  fiyat VARCHAR(60) NULL,
  one_cikar TINYINT(1) NOT NULL DEFAULT 0,
  sira INT NOT NULL DEFAULT 0,
  aktif TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS ustalar (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kullanici_id INT UNSIGNED NOT NULL UNIQUE,
  ad_soyad VARCHAR(100) NOT NULL,
  slug VARCHAR(140) NOT NULL UNIQUE,
  meslek VARCHAR(100) NOT NULL,
  telefon VARCHAR(20) NOT NULL,
  whatsapp VARCHAR(20) NULL,
  hakkinda TEXT NULL,
  tecrube_yil SMALLINT UNSIGNED NULL,
  kesif_ucretsiz TINYINT(1) NOT NULL DEFAULT 0,
  acil_hizmet TINYINT(1) NOT NULL DEFAULT 0,
  belgeli TINYINT(1) NOT NULL DEFAULT 0,
  belge_dosya VARCHAR(255) NULL,
  foto VARCHAR(255) NULL,
  durum ENUM('beklemede','aktif','askida','reddedildi') NOT NULL DEFAULT 'beklemede',
  red_nedeni VARCHAR(255) NULL,
  paket_id INT UNSIGNED NULL,
  paket_bitis DATE NULL,
  puan DECIMAL(2,1) NOT NULL DEFAULT 0,
  yorum_sayisi INT UNSIGNED NOT NULL DEFAULT 0,
  olusturma DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (kullanici_id) REFERENCES kullanicilar(id) ON DELETE CASCADE,
  FOREIGN KEY (paket_id) REFERENCES paketler(id) ON DELETE SET NULL,
  INDEX (durum)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS usta_hizmet (
  usta_id INT UNSIGNED NOT NULL,
  hizmet_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (usta_id, hizmet_id),
  FOREIGN KEY (usta_id) REFERENCES ustalar(id) ON DELETE CASCADE,
  FOREIGN KEY (hizmet_id) REFERENCES hizmetler(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS usta_ilce (
  usta_id INT UNSIGNED NOT NULL,
  ilce_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (usta_id, ilce_id),
  FOREIGN KEY (usta_id) REFERENCES ustalar(id) ON DELETE CASCADE,
  FOREIGN KEY (ilce_id) REFERENCES ilceler(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fotograflar (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  usta_id INT UNSIGNED NOT NULL,
  dosya VARCHAR(255) NOT NULL,
  olusturma DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usta_id) REFERENCES ustalar(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS yorumlar (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  usta_id INT UNSIGNED NOT NULL,
  ad VARCHAR(80) NOT NULL,
  mahalle VARCHAR(80) NULL,
  puan TINYINT UNSIGNED NOT NULL,
  metin TEXT NOT NULL,
  durum ENUM('beklemede','yayinda','gizli') NOT NULL DEFAULT 'beklemede',
  usta_yaniti TEXT NULL,
  ip VARCHAR(45) NULL,
  olusturma DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usta_id) REFERENCES ustalar(id) ON DELETE CASCADE,
  INDEX (durum)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS talepler (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  usta_id INT UNSIGNED NOT NULL,
  ad VARCHAR(80) NOT NULL,
  telefon VARCHAR(20) NOT NULL,
  ilce_id INT UNSIGNED NULL,
  mesaj TEXT NOT NULL,
  durum ENUM('yeni','goruldu','yanitlandi') NOT NULL DEFAULT 'yeni',
  ip VARCHAR(45) NULL,
  olusturma DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usta_id) REFERENCES ustalar(id) ON DELETE CASCADE,
  FOREIGN KEY (ilce_id) REFERENCES ilceler(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;

CREATE TABLE IF NOT EXISTS paket_talepleri (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  usta_id INT UNSIGNED NOT NULL,
  paket_id INT UNSIGNED NOT NULL,
  durum ENUM('yeni','gorusuldu') NOT NULL DEFAULT 'yeni',
  olusturma DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usta_id) REFERENCES ustalar(id) ON DELETE CASCADE,
  FOREIGN KEY (paket_id) REFERENCES paketler(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Günlük sayaçlar: profil görüntülenme, arama ve WhatsApp tıklamaları
CREATE TABLE IF NOT EXISTS olaylar (
  usta_id INT UNSIGNED NOT NULL,
  tur ENUM('goruntuleme','arama','whatsapp') NOT NULL,
  tarih DATE NOT NULL,
  adet INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (usta_id, tur, tarih),
  FOREIGN KEY (usta_id) REFERENCES ustalar(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Günlük hizmet arama sayaçları ("Samsun bu hafta ne arıyor?")
CREATE TABLE IF NOT EXISTS aramalar (
  hizmet_id INT UNSIGNED NOT NULL,
  tarih DATE NOT NULL,
  adet INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (hizmet_id, tarih),
  FOREIGN KEY (hizmet_id) REFERENCES hizmetler(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ayarlar (
  anahtar VARCHAR(60) PRIMARY KEY,
  deger TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_turkish_ci;
